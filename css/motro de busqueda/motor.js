    // Generar todas las tarjetas
    function renderAllProducts() {
      productosContainer.innerHTML = '';
      Object.keys(productos).forEach(key => {
        const id = parseInt(key);
        const prod = productos[id];
        const card = document.createElement('a');
        card.href = `./productoinfo.html?id=${id}`;
        card.classList.add('product-card');
        card.innerHTML = `
          <img src="${prod.imagenes[0].trim()}" alt="${prod.nombre}">
          <h3>${prod.nombre}</h3>
          <p>${prod.presentacion ? prod.presentacion[0] : 'Producto'}</p>
          <p>Precio online <span class="price">${prod.precio.promo}</span></p>
          <div class="icons"><i class="fa fa-truck"></i><i class="fa fa-store"></i></div>
          <button class="add-btn"><i class="fa fa-cart-plus"></i> Agregar</button>
        `;
        productosContainer.appendChild(card);
      });
    }

    // Mostrar sugerencias
    function showSuggestions(term) {
      suggestionsBox.innerHTML = '';
      if (!term) {
        suggestionsBox.style.display = 'none';
        return;
      }

      const filtered = Object.keys(productos)
        .map(key => ({ id: key, ...productos[key] }))
        .filter(prod => 
          prod.nombre.toLowerCase().includes(term.toLowerCase()) ||
          (prod.descripcion && prod.descripcion.join(' ').toLowerCase().includes(term.toLowerCase()))
        );

      if (filtered.length === 0) {
        suggestionsBox.style.display = 'none';
        return;
      }

      filtered.forEach(prod => {
        const item = document.createElement('div');
        item.classList.add('suggestion-item');
        item.innerHTML = `
          <img src="${prod.imagenes[0].trim()}" alt="${prod.nombre}">
          <div class="suggestion-info">
            <h4>${prod.nombre}</h4>
            <span class="price">${prod.precio.promo}</span>
          </div>
        `;
        item.onclick = () => {
          window.location.href = `./productoinfo.html?id=${prod.id}`;
        };
        suggestionsBox.appendChild(item);
      });

      suggestionsBox.style.display = 'block';
    }

    // Eventos
    searchInput.addEventListener('input', function() {
      const term = this.value.trim();
      showSuggestions(term);
    });

    document.addEventListener('click', function(e) {
      if (!suggestionsBox.contains(e.target) && e.target !== searchInput) {
        suggestionsBox.style.display = 'none';
      }
    });

    // Renderizar productos al cargar
    renderAllProducts();
